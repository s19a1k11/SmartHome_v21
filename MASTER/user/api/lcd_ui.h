#ifndef _LCD_UI_H
#define _LCD_UI_H

#include "common.h"

/*
	LCD 界面层 —— 把从机数据排版显示到 1.8 寸屏
	==================================================================
	屏幕: 128 x 160 竖屏, ST7735S

	布局设计 (16 号字体, 每字符 8x16 像素):
	┌────────────────────────┐ y=0
	│ SmartHome   v22        │  标题栏 (蓝底白字)
	├────────────────────────┤ y=16
	│ #1 ONLINE              │  y=20  从机1 状态行
	│ T:24.2 H:31.0          │  y=38
	│ Lux:3719 LED:0         │  y=56
	├────────────────────────┤ y=74
	│ #2 ONLINE              │  y=78
	│ T:25.8 H:38.0          │  y=96
	│ Lux:3720 LED:0         │  y=114
	├────────────────────────┤ y=132
	│ Hum:0 Night:0          │  y=136  SR602 + 夜晚判定
	│ Cloud:OK               │  y=150  云端连接状态
	└────────────────────────┘ y=160

	★ 刷新策略(关键, 避免拖慢轮询):
	  全屏填充 128x160 = 40960 次 SPI 字节写, 实测约 150ms。
	  每秒都全屏重绘会把 1 秒的轮询周期吃掉 15%。
	  所以:
	    1. 开机只做一次全屏清屏 + 画静态标题
	    2. 之后每秒只【局部重绘变化的区域】
	    3. 用 s_last 缓存上次显示的值, 值没变就不重绘
*/

/* 初始化: 清屏 + 画静态框架。在 LCD_Init() 之后调用一次。 */
void LCD_UI_Init(void);

/*
	刷新显示。主循环里调用, 内部自带 1 秒节流。
	返回: 1 = 本次有更新 / 0 = 没到时间或没变化
*/
u8 LCD_UI_Update(void);

/*
	强制立刻全量刷新(调试用, 比如 @lcd 命令)
*/
void LCD_UI_Refresh_All(void);

#endif
