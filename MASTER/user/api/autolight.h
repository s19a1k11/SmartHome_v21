#ifndef _AUTOLIGHT_H
#define _AUTOLIGHT_H

#include "common.h"
#include "modbus.h"

/*
	夜晚回家自动开灯 —— 只在主机实现
	==================================================================
	需求: "SR602 检测到人的同时, 如果检测到外界光照强度小于某个值
	      也就是判定为晚上的时候, 可以自动开灯"

	★ 执行器: 1 号从机的灯(寄存器 0x0200)
	  为什么是 1 号从机的灯:
	    SR602 在门口, 要开的是"门口的灯"; 灯接在从机 1 上,
	    主机通过 ModBus 写 0x0200 = 1 让它亮。
	    主机自己不开灯 —— 主机是总控, 装在总控箱里, 没有可控的照明负载。

	★ 光照来源: 三台从机 0x0104 的平均值
	  为什么不只用 1 号从机:
	    单台光敏可能被遮挡(比如正好被柜子挡住)或坏了,
	    三台取平均能抗单点故障。
	  为什么要排除离线的从机:
	    离线从机的 light 字段是"最后一次读到的旧值", 可能已经几小时了。
	    拿旧值参与平均会把"现在是晚上"判断错 —— 所以只平均在线且
	    数据可信的那几台。一台都不在线时【不动作】(宁可不开灯,
	    也不能凭 0 或旧值乱开灯)。

	★ 判定逻辑(全部在主循环, 不在中断):
	    if (有人) and (光照 < 阈值) and (灯当前是灭的):
	        写 1 号从机 0x0200 = 1     -> 开灯
	    if (没人) and (已经过了关灯延时) and (灯是亮的):
	        写 1 号从机 0x0200 = 0     -> 关灯

	  为什么加"灯当前是灭的"这个条件:
	    避免每秒都往 485 上发一条写命令。灯已经亮了就什么都不做。
	    这既省总线, 也避免"灯被本地手动关掉后又被主机立刻打开"的打架。
*/

/*
	夜晚判定阈值 (0~4095, 12 位 ADC 原始值)
	-----------------------------------------------------------------
	★ 这个值必须现场标定, 不能照抄! 因为:
	    光敏模块的 AO 电压方向和分压比因模块而异 ——
	    有的模块"越亮电压越高", 有的相反; 同一型号不同批次也不一样。

	标定方法(5 分钟):
	  1) 白天拉开窗帘, 看串口日志里的 [LUX] avg=xxxx
	  2) 晚上关灯, 再看一次 [LUX] avg=xxxx
	  3) 取两者的中间值填到这里
	     如果白天读数和晚上读数接近, 说明模块方向反了,
	     把下面 LIGHT_INVERT 改成 1(它会把 4095 - 值 翻过来)

	默认 1500 是"室内正常照明"的经验中间值, 只作为上手起点。
*/
#define NIGHT_LIGHT_THRESHOLD   (1500)

/*
	光照方向翻转
	0 = 原始值(越亮数值越大)
	1 = 翻转(4095 - 原始值), 用于"越亮数值越小"的模块
*/
#define LIGHT_INVERT            (0)

/*
	人离开后延时多久关灯, 单位 ms
	为什么不是"人一走就关":
	  人在门口掏钥匙/换鞋时会短暂离开感应范围, 立刻关灯体验很差。
	  10 秒是"够你走进屋"和"不在门口傻等"之间的折中。
*/
#define AUTOLIGHT_OFF_DELAY_MS  (10000)

/* 初始化: 记录初始时刻 */
void AutoLight_Init(void);

/*
	主循环每轮调用一次
	参数: sr602_human = 1 表示当前检测到有人
	内部会:
	  1) 计算三台在线从机的光照平均值
	  2) 按"有人 + 夜晚 + 灯灭" 决定是否开灯
	  3) 按"无人 + 超时 + 灯亮" 决定是否关灯
	返回: 1 = 本轮动作了(开了或关了灯) / 0 = 没动作
*/
u8 AutoLight_Poll(u8 sr602_human);

/*
	取当前的平均光照值(供上报云端和日志使用)
	返回 0xFFFF 表示"没有任何一台从机在线且数据可信", 此时不参与判定
*/
u16 AutoLight_Avg_Light(void);

/* 当前是否判定为夜晚(1 = 夜晚) */
u8 AutoLight_Is_Night(void);

#endif
