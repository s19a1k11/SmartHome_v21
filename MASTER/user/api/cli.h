#ifndef _CLI_H
#define _CLI_H

#include "common.h"

/*
	串口1 模拟 MQTT 指令 (本地命令行)
	==================================================================
	★ 需求: "主机可以通过串口1 接收电脑上串口助手发送的数据,
	        来模拟 MQTT 的一些命令"

	用途: 不用连云平台、不用 ESP8266, 直接用串口助手敲一行命令,
	      就能验证【云端下发 -> JSON 解析 -> ModBus 写从机 -> 回读 -> 上报】
	      整条链路。这样在实验室调从机、调自动开灯、调舵机方向时,
	      不用每次都去平台上点按钮。

	★ 和真实 MQTT 的关系:
	  命令格式和云端下发【完全一致】—— 都是一行 JSON。
	  处理路径也完全一致: CLI 把这一行交给 Cloud_Handle_Downlink(),
	  也就是云端下发调的那个函数。所以用串口模拟通了,
	  接上云平台就一定通(除非 MQTT 层本身有问题)。

	用法(串口助手: 9600 8N1, 发送时勾"加回车换行"):

	    {"Led1":true}                       开 1 号从机的灯
	    {"Led1":false}                      关 1 号从机的灯
	    {"Beep1":true}                      1 号蜂鸣器响
	    {"SG90_1":"clockwise"}              1 号舵机顺时针(180 度)
	    {"SG90_1":"counter_clockwise"}      1 号舵机逆时针(0 度)
	    {"Led1":true,"Beep1":true}          一条命令做多件事
	    {"stm32":false,"Led1":true}         总使能关闭 -> 整条命令被忽略

	★ 额外提供几条【本地诊断命令】(不是 JSON, 以 @ 开头, 不会和云端命令冲突):

	    @help            列出所有命令
	    @stat            打印三台从机的完整状态(在线/温湿度/光照/灯/舵机)
	    @poll            立刻轮询一次全部从机(不等 1 秒节拍)
	    @upload          立刻上报一次云端(不等 15 秒节拍)
	    @autolight on    强制打开 1 号从机的灯(测试用)
	    @autolight off   强制关闭
	    @sr602           打印 SR602 当前状态和夜晚判定结果
	    @log on / @log off   打开/关闭逐帧日志(调试 ModBus 时用)
	    @version         打印固件版本和关键配置

	★ 为什么用 @ 前缀区分:
	  云端下发永远是 JSON(以 { 开头)。用 @ 开头就不会有任何歧义,
	  也不会出现"我敲错一个字符被当成 JSON 解析"的情况。

	★ 实现约束(和整个工程一致):
	  - 解析在主循环做, 不在中断里
	  - 所有输出走 LOG_* 进缓冲, 由 main 循环最后一步统一 Flush
	  - 不阻塞轮询: 一帧处理完立刻返回
*/

/* 单行命令的最大长度(含结尾) */
#define CLI_LINE_MAX (160)

/* 初始化(清状态) */
void CLI_Init(void);

/*
	主循环每轮调用一次
	检查 USART1 是否收到一整行, 有就解析并执行
	返回: 1 = 本轮处理了一条命令 / 0 = 没有命令
*/
u8 CLI_Poll(void);

/*
	逐帧日志开关
	1 = 打开(每笔 ModBus 事务都打 TX/RX 原始帧)
	0 = 关闭(只在出错时打)
	★ 打开后轮询会明显变慢(实测日志会吃掉约 89% 的周期),
	  这是刻意的 —— 调试就是要看细节, 慢一点无所谓。
*/
void CLI_Set_ModBus_Log(u8 on);
u8   CLI_Get_ModBus_Log(void);

#endif
