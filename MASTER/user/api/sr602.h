#ifndef _SR602_H
#define _SR602_H

#include "common.h"

/*
	SR602 人体红外感应模块 (数字输出型) —— 主机侧
	==================================================================
	★ 2026-10-24 从机侧移除, 只装在主机上。
	  理由(实际应用):
	    SR602 是"门口有没有人"的传感器, 实际装在家门内;
	    全屋只有门口这一台设备(主机/总控)需要它, 三台从机各接一个
	    既浪费又没意义 —— 从机装在各个房间里, 测的是房间而不是门口。

	  所以:
	    从机 0x0105 回到"保留、固定返回 0"
	    主机的 SR602 状态直接上报云端键 "SR602"(单值, 不带编号)
	    并且驱动"夜晚回家自动开灯"逻辑(见 autolight.c)

	接线(模块 3 针):
	    模块 VCC -> 3.3V 或 5V (按模块标注, 常见 3.3~5V 都能工作)
	    模块 GND -> GND   (必须和开发板共地, 否则输出电平漂)
	    模块 OUT -> SR602_GPIO_PIN (默认 PE2)

	输出电平(重要, 不同批次模块可能相反):
	    检测到人体 -> 输出高电平 1
	    无人       -> 输出低电平 0
	  如果实测"有人反而读到 0", 把下面的 SR602_ACTIVE_LEVEL 改成 0 即可,
	  不用改任何逻辑代码。

	★ 用外部中断(EXTI)而不是纯轮询:
	  中断优先级排在"接收"之后(见 main.c 的优先级表), 因为
	  人走到门口这个事件必须在几百毫秒内被抓住, 轮询 1 秒一拍
	  在极端情况下会漏掉"来了又走"。
	  但中断里【只记录电平和时刻】, 所有判断(夜晚/延时关灯)都在主循环做 ——
	  快进快出, 不在中断里做任何逻辑。
*/

/* ---------- 硬件绑定: 换引脚只改这三行 ---------- */
#define SR602_GPIO_PORT        GPIOE
#define SR602_GPIO_PIN         GPIO_Pin_2
#define SR602_RCC_GPIO_CLK     RCC_APB2Periph_GPIOE
#define SR602_EXTI_PORT_SRC    GPIO_PortSourceGPIOE
#define SR602_EXTI_PIN_SRC     GPIO_PinSource2
#define SR602_EXTI_LINE        EXTI_Line2
#define SR602_EXTI_IRQn        EXTI2_IRQn

/*
	有效电平: 检测到人时 OUT 是高还是低
	1 = 有人时输出高(绝大多数 SR602 模块)
	0 = 有人时输出低(少数模块或接法相反)
*/
#define SR602_ACTIVE_LEVEL     1

/*
	初始化: 下拉输入 + EXTI 双边沿中断

	★ 为什么是【下拉】而不是上拉(v21 修):
	  战神V1 的 PE2 是 KEY2 按键脚, 板载本身带上拉电阻。
	  如果代码也配上拉, 模块没插时引脚被拉高 -> 误判"一直有人"
	  -> 夜晚会开灯且永不关闭(灯亮一整夜)。
	  改下拉后, 模块没插/线断 -> 读低 -> "无人" -> 不会误开灯。
	  这是安全的失败方向。
	  SR602 的 OUT 是推挽输出, 内部下拉(约40k)不影响它驱动高电平。

	为什么双边沿:
	  上升沿 = 有人来了(开灯), 下降沿 = 人走了(开始延时关灯计时)。
	  只做单边沿就收不到"人走了"的事件, 关灯逻辑只能靠轮询补, 不干净。
*/
void SR602_Init(void);

/*
	读一次当前人体状态(直接读引脚, 不依赖中断)
	返回: 1 = 检测到有人 / 0 = 无人
	★ 内部已经处理了 SR602_ACTIVE_LEVEL 极性, 调用方拿到的是语义值
*/
u8 SR602_Read(void);

/*
	取走"电平发生过变化"的标志(读后清零)
	返回 1 表示自上次调用以来 SR602 输出变过(有人来了或走了)
	★ 主循环用它决定要不要立刻重算自动开灯逻辑
*/
u8 SR602_Take_Changed(void);

/*
	最近一次电平变化的时刻(Delay_GetMs 的毫秒值)
	用于判断"人已经走了多久", 实现延时关灯
*/
u32 SR602_Last_Edge_Ms(void);

/*
	当前缓存的人体状态(不读引脚, 直接返回中断/上次读取记下的值)
	返回: 1 = 有人 / 0 = 无人
	★ 为什么要有这个而不直接用 SR602_Read():
	  上报云端、自动开灯判断都在主循环里跑, 用的是"这一轮开始时看到的状态"。
	  如果每次判断都重新读引脚, 同一个循环里前后两次判断可能读到不同值
	  (人正好在这几十毫秒里走动), 逻辑就会自相矛盾。
	  所以主循环开头读一次、缓存下来, 之后全用缓存值。
*/
u8 SR602_Current(void);

/* 主循环每轮调用: 读引脚并更新缓存值 */
void SR602_Sample(void);

#endif
