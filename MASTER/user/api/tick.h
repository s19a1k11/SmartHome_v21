#ifndef _TICK_H
#define _TICK_H

#include "common.h"

/*
	主机轮询节拍定时器 (TIM4)
	==================================================================
	★ 先回答一个关键问题: 定时器够不够用?
	  主机目前只占用 SysTick(delay.c 的 1ms 时基)。
	  TIM2 / TIM3 / TIM4 / TIM5 / TIM6 / TIM7 六个基本/通用定时器全空着。
	  所以【完全够用】, 而且值得用 —— 下面说明为什么比"条件判断"好。

	用定时器而不是 if(now - last >= 1000) 的真正理由:
	  条件判断的问题不是精度, 而是【主循环被长时间阻塞时无法察觉】。
	  主机的 Cloud_Link_Build() 在建链失败时会阻塞几十秒(ESP8266 入网
	  超时 + 重试)。这段时间里:
	    - 条件判断: 回来之后只看到"过去了 30 秒", 于是立刻轮询一次,
	                然后 last = now。它【无法知道】自己错过了 30 次轮询。
	    - 定时器:   回来之后读到 tick_cnt 涨了 30, 立刻就知道
	                "我错过了 30 个节拍, 这段时间的离线判定不可信",
	                可以据此跳过本轮判定, 避免把"我没去看"误当成"从机不在"。
	  这一点对"连续两次采集失败判离线"这条需求是硬性的:
	  如果主循环卡了 30 秒, 回来只轮询 1 次就判失败 1 次,
	  再 1 秒判失败 2 次 -> 报离线。可实际上从机可能一直是好的,
	  只是主机自己没空去看。有了 missed tick 计数就能区分这两种情况。

	实现要点:
	  定时器中断【只做一件事】: tick_cnt++ / 置标志。
	  真正的轮询(3 台 x 3 笔事务, 最坏 600ms)绝对不能放中断里 ——
	  那会把主循环彻底卡死, MQTT 心跳和下行全都停摆。
*/

/* 轮询节拍周期, 单位 ms。1 秒一拍 = 每秒把三台从机全扫一遍 */
#define TICK_PERIOD_MS   (1000)

/*
	初始化 TIM4 为 1 秒周期中断
	时钟链: APB1 = 36MHz, 但 APB1 预分频 != 1 时定时器时钟 = 2 x PCLK1 = 72MHz
	        PSC = 7200-1  -> 72MHz / 7200 = 10kHz (1 格 = 100us)
	        ARR = 10000-1 -> 10kHz 数 10000 次 = 1 秒
*/
void Tick_Init(void);

/*
	取走"有一个节拍到点"的标志(读后清零)
	调用者: main 循环。返回 1 表示该轮询了
*/
u8 Tick_Take(void);

/*
	取走"错过的节拍数"(读后清零)
	用法: 轮询之前先取, 如果 > 0 说明主循环刚才被长时间阻塞过,
	      这一轮的离线判定要跳过(详见 tick.c 顶部说明)
*/
u16 Tick_Take_Missed(void);

/* 累计节拍数(上电以来的秒数), 只读 */
u32 Tick_Count(void);

#endif
