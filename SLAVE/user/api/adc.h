#ifndef _ADC_H
#define _ADC_H

#include "common.h"

/*
	【卡10】光照采集: 光敏模块 AO -> PA1 (ADC1_IN1)
	-----------------------------------------------------------------
	为什么选 PA1 而不是最常见的 PA0:
		PA0 上面挂着板载 WK_UP 按键, 一按就被拉到 3.3V, 会污染读数;
		PA1 没有任何板载器件占用, 是这片板子上最干净的一路 ADC。
		如果你的模块 AO 已经插在别的脚, 只要改 adc.c 里三处
		(GPIO_Pin_x / ADC_Channel_x / CRL 或 CRH 的移位), 其余不用动。

	接线(3 针和 4 针模块都一样, 只用 AO 这一根):
		模块 VCC -> 3.3V
		模块 GND -> GND      (必须共地)
		模块 AO  -> PA1      (AO = 模拟量输出)
		模块 DO  -> 不接      (DO 是比较器输出的数字开关量, 这里不用)

	读出来的数:
		0 ~ 4095 (12 位), 对应 0 ~ 3.3V
		实际电压 = 返回值 * 3.3 / 4095

	方向(重要):
		光照变强时 AO 电压是升高还是降低, 取决于模块上光敏电阻和
		固定电阻谁在上面, 不同模块不一样。接上以后用手电筒照一下,
		看数值是变大还是变小就知道了。
		如果和你想要的"越亮数值越大"相反, 在 ModBus_Get_Reg 里
		改成 return 4095 - g_light; 就翻过来了, 不用改这里。
*/

/* 初始化 PA1 为模拟输入 + ADC1 单通道单次转换, 只调用一次 */
void Light_Init(void);

/* 读一次光照, 返回 0~4095 (内部已经做了 8 次平均滤波) */
u16  Light_Read(void);

#endif
