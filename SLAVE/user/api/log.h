#ifndef _LOG_H
#define _LOG_H

#include "common.h"

/*
	调试日志缓冲 (USART1 = 调试回显口)
	==================================================================
	★ 本工程的硬要求:
	  "串口1 作为调试数据回显, 必须在所有需要完成的操作结束后再发送"

	为什么必须延后:
	  USART1 是 9600 阻塞发送, 1 个字符约 1.04ms。
	  如果一边采传感器/一边应答 485 就一边打印, 打印时间会直接叠加到
	  485 应答延迟上 —— 打 40 个字符就是 40ms, 而主机只等 200ms,
	  三次两回就把超时预算吃光了。
	  更糟的是采集节拍里连打三行, 那 2 秒一拍就会周期性拖慢总线响应。

	做法:
	  所有日志先写进 RAM 缓冲 (LOG_Str / LOG_Num / LOG_Hex 都只是 memcpy 级操作),
	  主循环把该做的事(采集 / 应答 / 上报 / 下发)全部做完之后,
	  最后一步才调 LOG_Flush() 真正往 USART1 发。
	  这样无论日志多少, 都不会挡在时序关键路径上。

	★ 使用约束:
	  1) 只允许在主循环上下文调用, 绝对不许在中断里调(ISR 里连 LOG_Str 都不许)
	  2) LOG_Flush() 是阻塞的, 一个循环里只调一次, 放在最后
	  3) 缓冲满了会丢新内容并打截断标记, 不会越界、也不会卡住
*/

/* 缓冲大小: 一次循环里最多攒多少字节日志。1024 约等于 1 秒的串口发送量 */
#define LOG_BUF_SIZE (1024)

/* 初始化: 清空缓冲。必须在 USART1_Init 之后调用 */
void LOG_Init(void);

/* 追加一个字符串(不发送) */
void LOG_Str(const char *s);

/* 追加一个字符 */
void LOG_Chr(char c);

/* 追加一个 0~65535 的十进制数字 */
void LOG_Num(u16 n);

/* 追加一个 4 位十六进制(不带 0x 前缀) */
void LOG_HexNum(u16 v);

/*
	追加形如 "TAG[08]: 01 03 ... \r\n" 的十六进制转储
	tag 不能是 NULL, buf 长度由 len 给出
*/
void LOG_HexDump(const char *tag, u8 *buf, u16 len);

/*
	把缓冲里的内容真正发到 USART1, 然后清空
	★ 这是唯一会产生阻塞的地方, 必须在"所有需要完成的操作结束后"调用
	缓冲为空时立刻返回, 不做任何 IO
*/
void LOG_Flush(void);

/* 缓冲里还有没有待发内容(1 = 有) */
u8 LOG_Pending(void);

#endif
