#ifndef _485_PD7_H
#define _485_PD7_H

#include "common.h"

/*
	RS485 半双工方向控制脚 PD7
	==================================================================
	PD7 输出 1 = 发送使能(占用总线)
	PD7 输出 0 = 接收使能(释放总线)

	★ 设计约束(本项目硬要求): 全工程【只有本文件】可以碰 PD7。
	  任何其它文件都不许出现 GPIOD / GPIO_Pin_7 去控制方向,
	  只能调用 My_485_Tx() / My_485_Rx()。

	为什么必须收敛到一处:
		方向脚是"独占资源", 一旦有两处代码都能改它, 就会出现
		"A 函数切到发送 -> B 函数也切了一次 -> 谁负责切回来" 的责任真空。
		表现是: 某个分支之后总线一直被本机拉死, 所有从机都不应答,
		复位才好, 而且只在特定时序下复现 —— 这类 bug 极难定位。
		收敛到一个文件之后, "谁切了谁切回来" 变成可以在 60 行代码里看完的事。

	为什么"发送态"要等 TC 而不是 TXE:
		TXE(发送数据寄存器空)只代表"DR 里的字节被搬进了移位寄存器",
		最后一个字节的停止位可能还没移出去。此时立刻拉低 PD7,
		总线上最后半个字节会被切断, 对端收到的是残帧 -> CRC 必败。
		TC(发送完成)才是"整个字节连停止位都出去了"。
*/

/* 485 方向脚初始化: 配置 PD7 为推挽输出, 并立刻置为接收态 */
void My_485_Init(void);

/* 切到发送态(PD7 = 1), 调用后立刻可以往 USART2 写数据 */
void My_485_Tx(void);

/* 切回接收态(PD7 = 0), 必须在确认最后一个字节已发送完成(TC=1)之后调用 */
void My_485_Rx(void);

/*
	发送一整帧并自动完成方向切换
	内部顺序: 切发送 -> 逐字节发送 -> 等 TC -> 切接收
	调用方不需要(也不应该)自己再碰 PD7

	★ 为什么要单独提供这个函数而不是让调用方自己 Tx/Rx 配对:
	  配对调用很容易在某个提前 return 的分支上漏掉 Rx,
	  一旦漏掉总线就被占死。封装成一个函数, 出口只有一个。
*/
void My_485_SendBuffer(u8 *buf, u16 len);

#endif
