#ifndef _SERVO_H
#define _SERVO_H

#include "common.h"

/*
	【卡9】SG90 舵机 PWM 驱动
	-----------------------------------------------------------------
	信号线 -> PA7 (TIM3_CH2, 不做重映射)
	50Hz(周期 20ms), 高电平脉宽 0.5~2.5ms 对应 0~180 度
	时基: 72MHz/72 = 1MHz -> 1 格 = 1us; ARR=20000-1 -> 20ms

	注意: 舵机电源用 5V, 地线必须和开发板共地。
	      不要用 3.3V 供电, SG90 堵转电流能到 700mA 以上, 会拉垮板子。
*/

/* 初始化: 只会被调用一次, 上电后舵机自动回 90 度中位 */
void Servo_Init(void);

/*
	设置档位: 0 -> 0 度 / 1 -> 90 度 / 2 -> 180 度
	传 3 以上直接忽略, 舵机不动
*/
void Servo_Set_Angle(u8 idx);

#endif
